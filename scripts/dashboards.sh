#!/bin/sh
# Grafana dashboards: dashboards/*.json is the source; Argo CD applies a
# ConfigMap per dashboard from gitops/manifests/monitoring/ (label
# grafana_dashboard=1, which Grafana's sidecar loads).
#
#   scripts/dashboards.sh gen     write the ConfigMaps from dashboards/*.json
#   scripts/dashboards.sh check   CI: ConfigMaps up to date, every panel has a
#                                 description, every PromQL query parses
#
# Needs jq and Docker.
set -eu
cd "$(dirname "$0")/.."

PROM_IMAGE=prom/prometheus:v3.16.0@sha256:e04987641b57704f408e31f6373ba4138ecf27cb4a165d24aabb6c38fddd0f06
OUT=gitops/manifests/monitoring

configmap() { # configmap <dashboard.json>
  name=$(basename "$1" .json)
  cat <<EOF
# Generated by scripts/dashboards.sh from dashboards/$name.json. Don't edit;
# edit the JSON and run: scripts/dashboards.sh gen
apiVersion: v1
kind: ConfigMap
metadata:
  name: dashboard-$name
  namespace: monitoring
  labels:
    grafana_dashboard: "1"
    app.kubernetes.io/part-of: orders-gateway-platform
data:
  $name.json: |
EOF
  jq . "$1" | sed 's/^/    /'
}

case "${1:-}" in
  gen)
    for f in dashboards/*.json; do
      configmap "$f" >"$OUT/dashboard-$(basename "$f" .json).yaml"
      echo "wrote $OUT/dashboard-$(basename "$f" .json).yaml"
    done
    ;;
  check)
    failed=0
    for f in dashboards/*.json; do
      name=$(basename "$f" .json)
      # 1. The committed ConfigMap matches the JSON.
      if ! configmap "$f" | cmp -s - "$OUT/dashboard-$name.yaml"; then
        echo "FAIL $f: $OUT/dashboard-$name.yaml is out of date; run scripts/dashboards.sh gen"; failed=1
      fi
      # 2. Every panel (rows aside) says what it measures.
      missing=$(jq -r '.. | objects | select(has("panels")) | .panels[] | select(.type != "row") | select((.description // "") == "") | .title' "$f")
      if [ -n "$missing" ]; then
        echo "FAIL $f: panels without a description:"; echo "$missing" | sed 's/^/  - /'; failed=1
      fi
      # 3. Every Prometheus query parses: wrap them as recording rules (with
      #    Grafana's variables filled in) and let promtool check them. This
      #    also covers annotation queries, which carry an "expr" too. This
      #    checks that queries parse, not that they return data. Piped
      #    in on stdin: no bind mount, so it works the same under Colima.
      # shellcheck disable=SC2016 # $n and $namespace etc. are jq/Grafana's
      jq -r --arg n "$name" '
        [.. | objects | select(has("expr")) | select((.datasource.type // "prometheus") == "prometheus") | .expr]
        | {groups: [{name: $n, rules: (to_entries | map({record: "dashboard:q\(.key)", expr: .value}))}]}' "$f" |
        sed -e 's/\${namespace}/prod/g' -e 's/\$__rate_interval/2m/g' -e 's/\$__interval/30s/g' -e 's/\$namespace/prod/g' |
        docker run --rm -i --entrypoint promtool "$PROM_IMAGE" check rules || { echo "FAIL $f: a query doesn't parse (above)"; failed=1; }
    done
    [ "$failed" -eq 0 ] && echo "dashboards: all checks passed"
    exit "$failed"
    ;;
  *) echo "usage: scripts/dashboards.sh gen|check" >&2; exit 2 ;;
esac
